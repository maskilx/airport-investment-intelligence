"""Run the validation-case SQL files in docs/examples and render their actual results.

    python -m airport_data.examples [--out docs/examples/RESULTS.md]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from .config import REPO_ROOT, get_paths
from .db import connect

EXAMPLES = REPO_ROOT / "docs" / "examples"


def split_statements(sql: str) -> list[str]:
    body = "\n".join(l for l in sql.splitlines() if not l.strip().startswith("--"))
    return [s.strip() for s in body.split(";") if s.strip()]


def run_file(con, path: Path) -> list[tuple[str, list[str], list[tuple]]]:
    out = []
    for stmt in split_statements(path.read_text()):
        cur = con.execute(stmt)
        if stmt.upper().startswith("SET "):
            continue
        cols = [d[0] for d in cur.description]
        out.append((stmt, cols, cur.fetchall()))
    return out


def to_markdown(cols, rows, limit=40) -> str:
    fmt = lambda v: "" if v is None else (f"{v:,}" if isinstance(v, int) and abs(v) >= 10000 else str(v))
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows[:limit]]
    if len(rows) > limit:
        lines.append(f"\n_({len(rows) - limit} more rows)_")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir")
    ap.add_argument("--out", default=str(EXAMPLES / "RESULTS.md"))
    a = ap.parse_args(argv)
    con = connect(get_paths(a.data_dir))
    built = con.execute("SELECT built_at, selected_raw_fingerprint FROM build_info").fetchone()
    fresh = con.execute("SELECT source_id, first_period, latest_period, freshness FROM v_source_freshness ORDER BY 1").fetchall()
    doc = ["# Validation-case query results (generated)", "",
           f"Generated by `python -m airport_data.examples` against a DB built at {built[0]} "
           f"(raw fingerprint `{built[1][:12]}`). These are **data-availability demonstrations**, not product answers.", "",
           "Source coverage at build time:", "", to_markdown(["source", "first", "latest", "freshness"], fresh), ""]
    for f in sorted(EXAMPLES.glob("q*.sql")):
        header = [l[3:] for l in f.read_text().splitlines() if l.startswith("-- ")][:2]
        doc += [f"## {f.stem}", "", f"_{' '.join(header)}_  — query: [`{f.name}`]({f.name})", ""]
        for i, (stmt, cols, rows) in enumerate(run_file(con, f), 1):
            doc += [f"**Result {i}** ({len(rows)} rows)", "", to_markdown(cols, rows), ""]
    Path(a.out).write_text("\n".join(doc))
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
